export function legalDoc(id: string): LegalDoc | null {
  switch (id) {
    case 'terms':
      return terms();
    case 'privacy':
      return privacy();
    case 'medical':
      return medical();
    case 'faq':
      return faq();
    default:
      return null;
  }
}
