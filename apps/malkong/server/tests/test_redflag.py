@pytest.mark.parametrize(("question", "months", "l1_id"), MUST_CATCH)
def test_catches(question: str, months: int, l1_id: str) -> None:
    assert l1_id in [h.l1_id for h in detect(question, months)]


@pytest.mark.parametrize(("question", "months"), MUST_PASS)
def test_passes(question: str, months: int) -> None:
    assert detect(question, months) == []


def test_three_month_fever_threshold_is_38() -> None:
    assert detect("37.9도예요", 2) == []
    assert [h.l1_id for h in detect("38도예요", 2)] == ["k-warn-0001"]


